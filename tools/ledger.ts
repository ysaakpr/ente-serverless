/**
 * TEST-LEDGER.md generator — from vitest JSON output, never hand-edited
 * (a hand-edited number is a lie waiting to be believed). Runs the unit +
 * infra suites; integration numbers come from the last `make test-int` run
 * only when LocalStack is up (marked accordingly).
 */

import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';

interface VitestJson {
  testResults: Array<{ name: string; assertionResults: Array<{ status: string }> }>;
}

const run = (args: string[]): VitestJson => {
  try {
    const out = execFileSync('npx', ['vitest', 'run', ...args, '--reporter=json'], {
      encoding: 'utf8',
      maxBuffer: 64 * 1024 * 1024,
    });
    return JSON.parse(out.slice(out.indexOf('{'))) as VitestJson;
  } catch (err) {
    const out = (err as { stdout?: string }).stdout ?? '';
    return JSON.parse(out.slice(out.indexOf('{'))) as VitestJson;
  }
};

